function hasArabic(value: string) {
  return /[\u0600-\u06ff]/.test(value);
}

function translate(value: string) {
  const trimmed = value.trim();
  if (!trimmed || !hasArabic(trimmed)) return value;

  const exact = TEXT[trimmed];
  if (exact) return value.replace(trimmed, exact);

  let next = value;
  for (const [ar, en] of Object.entries(TEXT)) {
    if (next.includes(ar)) next = next.split(ar).join(en);
  }
  if (next !== value) return next;

  for (const [ar, en] of Object.entries(PARTIAL)) {
    next = next.split(ar).join(en);
  }
  return next;
}

function shouldSkip(node: Node) {
  const parent = node.parentElement;
  if (!parent) return true;
  return !!parent.closest("script,style,textarea,code,pre,[data-no-auto-translate]");
}

function translateTextNode(node: Node) {
  if (shouldSkip(node)) return;
  const current = node.nodeValue ?? "";
  const next = translate(current);
  if (next !== current) node.nodeValue = next;
}

function translateElement(element: Element) {
  if (element.closest("script,style,textarea,code,pre,[data-no-auto-translate]")) return;
  for (const attr of ["placeholder", "aria-label", "title"]) {
    const current = element.getAttribute(attr);
    if (current) {
      const next = translate(current);
      if (next !== current) element.setAttribute(attr, next);
    }
  }
  if (element.getAttribute("dir") === "rtl") element.setAttribute("dir", "ltr");
}

function translateTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node);
    node = walker.nextNode();
  }
  if (root instanceof Element) translateElement(root);
  root.querySelectorAll?.("[placeholder],[aria-label],[title],[dir='rtl']").forEach(translateElement);
}

export function enableEnglishDomAutoTranslate() {
  if (typeof document === "undefined") return () => {};
  translateTree(document.body);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target);
      for (const node of mutation.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        if (node instanceof Element) translateTree(node);
      }
      if (mutation.type === "attributes" && mutation.target instanceof Element) {
        translateElement(mutation.target);
      }
    }
  });

  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "aria-label", "title", "dir"],
  });

  return () => observer.disconnect();
}
